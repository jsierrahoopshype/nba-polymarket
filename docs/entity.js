/* ==========================================================================
   Entity page renderer (player / team).

   The static page (generated by scripts/build_entities.py) carries the SEO
   shell — title, meta, heading, image, and a crawlable list of the entity's
   market questions in #markets — plus window.ENTITY with the matched market
   ids. This script swaps that static list for the live, volume-sorted table
   pulled from index.json, reusing the shared helpers in app.js. If anything
   fails, the static list stays put.
   ========================================================================== */
(async function () {
  const E = window.ENTITY || {};
  const wrap = document.getElementById('markets');
  const foot = document.getElementById('foot');
  if (!wrap || !E.ids || !E.ids.length) return;   // no markets -> keep static msg

  let data;
  try { data = await loadData('index.json'); }
  catch (e) { return; }                            // keep the static SEO list
  await loadEntities();                            // for cross-links to other entities

  const norm = computeNormalized(data.markets);
  const byId = new Map((data.markets || []).map(m => [m.conditionId, m]));
  let mk = E.ids.map(id => byId.get(id)).filter(Boolean);
  if (!mk.length) return;                          // all dropped from index; keep static
  mk.sort((a, b) => (b.volume || 0) - (a.volume || 0));

  const passing = mk.filter(passesFloor);
  const allLow = passing.length === 0;   // nothing clears the floor
  let showLow = allLow;                   // ...so show everything rather than a blank list

  function rowsFor(list) {
    return list.map(m => {
      const d24 = fmtDelta(m.delta24h), d7 = fmtDelta(m.delta7d);
      return '<tr data-id="' + esc(m.conditionId) + '">' +
        '<td class="name">' + entityThumb(m.conditionId) +
          '<span class="q">' + settledBadge(m) + esc(displayTitle(m)) + '</span>' +
          '<span class="ev">' + esc(m.eventTitle || '') + '</span>' + entityChips(m.conditionId) + '</td>' +
        '<td class="vol">' + fmtVol(m.volume) + '</td>' +
        '<td class="spark">' + sparkline(m.sparkline) + '</td>' +
        '<td class="pct">' + probHtml(m, norm) + '</td>' +
        '<td><span class="delta ' + d24.cls + '">' + d24.text + '</span></td>' +
        '<td><span class="delta ' + d7.cls + '">' + d7.text + '</span></td>' +
      '</tr>';
    }).join('');
  }

  function cardsFor(list) {
    return list.map(m => {
      const d24 = fmtDelta(m.delta24h), d7 = fmtDelta(m.delta7d);
      return '<div class="card" data-id="' + esc(m.conditionId) + '">' +
        '<div class="now"><span class="p">' + probHtml(m, norm) + '</span></div>' +
        '<div class="q">' + entityThumb(m.conditionId) + settledBadge(m) + esc(displayTitle(m)) + '</div>' +
        '<div class="ev">' + esc(m.eventTitle || '') + '</div>' + entityChips(m.conditionId) +
        '<div class="card-foot">' +
          '<span class="lbl">Vol</span><span>' + fmtVol(m.volume) + '</span>' +
          '<span class="lbl">24h</span><span class="delta ' + d24.cls + '">' + d24.text + '</span>' +
          '<span class="lbl">7d</span><span class="delta ' + d7.cls + '">' + d7.text + '</span>' +
          (m.sparkline && m.sparkline.length >= 2 ? sparkline(m.sparkline) : '') +
        '</div></div>';
    }).join('');
  }

  function draw() {
    const vis = (showLow || allLow) ? mk : passing;
    const hidden = mk.length - passing.length;
    let bar = '';
    if (allLow) {
      // every market is below the floor — show them all with a plain note, no toggle
      bar = '<div class="lowvol-note">All ' + mk.length + ' market' + (mk.length === 1 ? '' : 's') +
            ' here are under $' + (MIN_VOLUME / 1000) + 'K.</div>';
    } else if (hidden > 0) {
      bar = '<div class="lowvol-bar"><button class="lowvol-toggle' + (showLow ? ' active' : '') +
            '" id="elv">' + (showLow ? 'Hide low-volume markets' : 'Show low-volume markets') + '</button>' +
            '<span class="lowvol-note">' + (showLow
              ? 'Showing all ' + mk.length + ' markets.'
              : hidden + ' under $' + (MIN_VOLUME / 1000) + 'K hidden.') + '</span></div>';
    }
    wrap.innerHTML = bar +
      '<div class="table-wrap"><table class="lb"><thead><tr>' +
        '<th class="left">Market</th><th>Vol</th><th>Trend</th><th>Now</th><th>24h</th><th>7d</th>' +
        '</tr></thead><tbody>' + rowsFor(vis) + '</tbody></table></div>' +
      '<div class="cards">' + cardsFor(vis) + '</div>';
    wireRowNav(wrap);
    const b = document.getElementById('elv');
    if (b) b.addEventListener('click', () => { showLow = !showLow; draw(); });
  }

  draw();
  if (foot) {
    foot.innerHTML = mk.length + ' market' + (mk.length === 1 ? '' : 's') +
      ' · data from Polymarket · updated ' + fmtStamp(data.lastUpdated);
  }
})();
